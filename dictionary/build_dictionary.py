CAT_EN = {
    "सर्वनाम": "pronouns",
    "परिवार": "family",
    "प्रकृति": "nature",
    "जगह": "place",
    "जानवर": "animals",
    "शरीर": "body",
    "खाना": "food",
    "संख्या": "numbers",
    "दैनिक": "everyday",
    "क्रिया": "verbs",
}


def main() -> None:
    entries = []
    for i, (hi, en, gon, cat, note) in enumerate(RAW, 1):
        entries.append(
            {
                "id": i,
                "hindi": hi,
                "english": en,
                "hindi_gondi": convert(hi),
                "gondi_deva": gon,
                "gondi_masaram": convert(gon),
                "category": cat,
                "category_en": CAT_EN.get(cat, cat),
                "note": note,
            }
        )

    data = {
        "name": "Hindi–Gondi everyday dictionary",
        "version": "1.0",
        "script": "Masaram Gondi (U+11D00–U+11D5F)",
        "disclaimer": (
            "Gondi has many dialects (Adilabad, Bastar, Mandla, Chandrapur…). "
            "Gondi-language glosses are commonly cited forms, not a single official standard. "
            "hindi_gondi is a phonetic Devanagari→Masaram rendering of the Hindi word itself."
        ),
        "count": len(entries),
        "categories": sorted({e["category"] for e in entries}),
        "entries": entries,
    }

    out_json = Path(__file__).with_name("gondi_hindi_dictionary.json")
    out_json.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")

    js_path = Path(__file__).resolve().parents[1] / "web" / "js" / "dictionary.js"
    js_path.parent.mkdir(parents=True, exist_ok=True)
    js_path.write_text(
        "/* auto-generated — do not edit by hand */\n"
        "window.GONDI_DICTIONARY = "
        + json.dumps(data, ensure_ascii=False)
        + ";\n",
        encoding="utf-8",
    )

    # compact markdown cheat-sheet
    lines = [
        "# हिन्दी ↔ गोंडी रोज़मर्रा शब्दकोश",
        "",
        f"{data['disclaimer']}",
        "",
        f"**{len(entries)} शब्द** · लिपि: मसराम गोंडी",
        "",
    ]
    current = None
    for e in entries:
        if e["category"] != current:
            current = e["category"]
            lines += ["", f"## {current}", "", "| हिन्दी | English | हिन्दी→मसराम | गोंडी (देवनागरी) | गोंडी (मसराम) | टिप्पणी |", "|---|---|---|---|---|---|"]
        lines.append(
            f"| {e['hindi']} | {e['english']} | {e['hindi_gondi']} | {e['gondi_deva']} | {e['gondi_masaram']} | {e['note']} |"
        )
    md = Path(__file__).with_name("gondi_hindi_dictionary.md")
    md.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out_json} ({len(entries)} entries)")
    print(f"Wrote {js_path}")
    print(f"Wrote {md}")


if __name__ == "__main__":
    main()
